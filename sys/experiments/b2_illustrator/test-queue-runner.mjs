import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {prepareRequests,collectResults} from './queue-runner.mjs';
import {AttemptStore} from './attempt-store.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'vp-queue-'));
const file=path.join(dir,'ref.png');fs.writeFileSync(file,'reference');
const request={testCase:'scene-1',prompt:'Borrow a book',ratio:'9:16',outDir:dir,characterRefPath:file,charMediaId:'mascot-id'};
test('reference content and media identity are captured',()=>{
 const [r]=prepareRequests([request]);assert.equal(r.character.mediaId,'mascot-id');assert.equal(r.identity.references.length,1);assert.equal(r.identity.references[0].sha256.length,64);
});
test('missing base media ID blocks before browser operations',()=>assert.throws(()=>prepareRequests([{...request,baseRefPath:file}]),/MEDIA_ID/));
test('duplicate scene IDs and oversized batches are rejected',()=>{
 assert.throws(()=>prepareRequests([request,request]),/DUPLICATE/);
 assert.throws(()=>prepareRequests(Array(5).fill(request)),/SIZE/);
});
test('ratio and character reference are required',()=>{
 assert.throws(()=>prepareRequests([{...request,ratio:'1:1'}]),/INVALID/);
 assert.throws(()=>prepareRequests([{...request,characterRefPath:null}]),/CHARACTER/);
});
test('collection-only mode preserves generation identity',()=>{
 assert.deepEqual(prepareRequests([request])[0].identity,prepareRequests([{...request,collectionOnly:true}])[0].identity);
});
test('collection failure retains generated bytes and cannot submit again after restart',()=>{
 const folder=path.join(dir,'recovery'),store=new AttemptStore(folder);
 const r=prepareRequests([{...request,testCase:'recovery'}])[0],a=store.prepare(r.identity);
 store.beginSubmission(a,{queueId:'queue-1',screenshot:null});
 store.recordGenerated(a,{mediaId:'known-media',result:{mimeType:'invalid/test',base64:'AAAA'}});
 assert.throws(()=>collectResults(store,[a],[r]),/OUTPUT_FORMAT/);
 const restarted=new AttemptStore(folder),saved=restarted.load(a);
 assert.equal(saved.state,'generated');assert.equal(saved.mediaId,'known-media');
 assert.equal(saved.events.at(-1).event,'collection_failed');
 assert.throws(()=>restarted.beginSubmission(saved),/Cannot transition/);
});
test.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
